import { expect, test } from '@playwright/test';
test('people heading editing and avatar drawing use one clear control each', async ({ page }) => {
  await page.goto('/'); await page.getByRole('button', {name:'Join free',exact:true}).click();
  const signup=page.getByRole('dialog',{name:'Create a free account'});
  await signup.getByLabel('Username',{exact:true}).fill(`avatar_${Date.now()}`);
  await signup.getByLabel('Password',{exact:true}).fill('a unique test password');
  await signup.getByLabel('Nickname',{exact:true}).fill('Avatar Player');
  await signup.getByRole('button',{name:'Create my free account'}).click();
  await expect(page).toHaveURL(/dashboard$/); await page.locator('.account-nav-button').click();
  await expect(page.getByRole('group',{name:'Pixel canvas',exact:true})).toHaveCount(0);
  await expect(page.locator('.avatar-picker .avatar-option')).toHaveCount(7);
  await page.getByRole('button',{name:'Draw custom avatar',exact:true}).click();
  await page.getByRole('button',{name:'Start from peach',exact:true}).click();
  const canvas=page.getByRole('group',{name:'Pixel canvas',exact:true});
  await canvas.focus(); await canvas.press('Enter');
  await page.getByRole('button',{name:'Done — save avatar',exact:true}).click();
  await expect(page.getByText('Your custom avatar is saved.',{exact:true})).toBeVisible();
  await expect(canvas).toHaveCount(0);
  await page.reload();
  await expect(page.getByRole('button',{name:'Edit custom avatar',exact:true})).toHaveAttribute('aria-pressed','true');
  const saved=await page.evaluate(async()=> (await (await fetch('/api/session')).json()).data.account.avatarDesign);
  expect(saved.pixels).toHaveLength(576);
  await page.getByRole('button',{name:'Edit custom avatar',exact:true}).click();
  await page.getByRole('button',{name:'Start from sun',exact:true}).click();
  await page.getByRole('button',{name:'Cancel drawing',exact:true}).click();
  const afterCancel=await page.evaluate(async()=> (await (await fetch('/api/session')).json()).data.account.avatarDesign);
  expect(afterCancel).toEqual(saved);
  await page.getByRole('button',{name:'sky avatar',exact:true}).click();
  await expect(page.getByRole('button',{name:'sky avatar',exact:true})).toHaveAttribute('aria-pressed','true');
  await page.getByRole('button',{name:'Save my profile',exact:true}).click();
  await expect(page.getByText('Your pixel you is saved. Looking good.',{exact:true})).toBeVisible();
  await page.reload(); await expect(page.getByRole('button',{name:'sky avatar',exact:true})).toHaveAttribute('aria-pressed','true');
  await page.route('**/api/people',async route=> {if(route.request().method()!=='GET')return route.continue();await route.fulfill({json:{ok:true,data:{categories:{special:'My special person',friends:'Friends'},connections:[{id:'special',accountId:'s',nickname:'Special Person',petName:'',avatar:'peach',avatarDesign:null,kind:'special'},{id:'friend1',accountId:'f1',nickname:'Friend One',petName:'',avatar:'moss',avatarDesign:null,kind:'friend'},{id:'friend2',accountId:'f2',nickname:'Friend Two',petName:'',avatar:'sky',avatarDesign:null,kind:'friend'}],invitations:[],blocked:[]}}});});
  await page.getByRole('link',{name:'Your people',exact:true}).click();
  await expect(page.locator('.people-category.special .people-person-row')).toHaveCount(1);
  await expect(page.locator('.people-category.friend .people-person-row')).toHaveCount(2);
  await expect(page.locator('.people-category .pill')).toHaveCount(0);
  await page.getByRole('button',{name:'Rename special-person category',exact:true}).click();
  await expect(page.getByRole('heading',{name:'My special person',exact:true})).toHaveCount(0);
  await expect(page.locator('.people-category.special .panel-heading input')).toHaveCount(1);
  await expect(page.locator('.people-category.special input#category-special')).toHaveValue('My special person');
  await page.getByLabel('Category name',{exact:true}).fill('My favourite');
  await page.getByLabel('Category name',{exact:true}).press('Escape');
  await expect(page.getByRole('heading',{name:'My special person',exact:true})).toBeVisible();
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:'test-results/people-rows-phone.png',fullPage:true});
});
