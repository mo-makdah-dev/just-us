import { test, expect } from '@playwright/test';
test('dashboard URLs, history, simplified settings and concurrent tabs', async ({ page, context }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Join free', exact: true }).click();
  const signup = page.getByRole('dialog', { name: 'Create a free account' });
  await signup.getByLabel('Username', { exact: true }).fill(`ux_${Date.now()}`);
  await signup.getByLabel('Password', { exact: true }).fill('a unique test password');
  await signup.getByLabel('Nickname', { exact: true }).fill('UX Player');
  await signup.getByRole('button', { name: 'Create my free account' }).click();
  await expect(page).toHaveURL(/\/dashboard$/);
  await expect(page.locator('footer')).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Refresh rooms & invitations' })).toHaveCount(0);
  await page.getByRole('button', { name: /Your people Friends/ }).click();
  await expect(page).toHaveURL(/\/account\?section=people$/);
  await page.getByRole('button', { name: 'My game scores', exact: true }).click();
  await expect(page).toHaveURL(/section=scores$/);
  await expect(page.getByRole('heading', { name: 'Tic-tac-toe', exact: true })).toHaveCount(0);
  await page.goBack();
  await expect(page.getByRole('heading', { name: 'Your people.', exact: true })).toBeVisible();
  await page.goBack(); await expect(page).toHaveURL(/\/dashboard$/);
  await page.goForward(); await expect(page.getByRole('heading', { name: 'Your people.', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Rename friends category' }).click();
  await page.getByLabel('Category name', { exact: true }).fill('My circle');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'My circle', exact: true })).toBeVisible();
  await expect(page.locator('.category-settings')).toHaveCount(0);
  await page.getByRole('button', { name: 'Account security', exact: true }).click();
  await expect(page.getByLabel('Current password', { exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Change', exact: true }).click();
  await expect(page.getByLabel('Current password', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Download my data' })).toHaveCount(0);
  await page.reload(); await expect(page.getByRole('heading', { name: 'Sign-in & security' })).toBeVisible();
  await page.getByRole('button', { name: 'Back to dashboard', exact: true }).click();
  await expect(page).toHaveURL(/\/dashboard$/);
  await page.getByRole('button', { name: 'Create a room', exact: true }).click();
  await page.mouse.click(2, 2);
  await expect(page.getByRole('dialog', { name: 'Create a room', exact: true })).not.toBeVisible();
  await page.getByRole('button', { name: 'Create a room', exact: true }).click();
  await page.getByRole('button', { name: 'Create our little room' }).click();
  await expect(page.getByText('Room connected', { exact: true })).toBeVisible();
  const second = await context.newPage(); await second.goto('/');
  await expect(second.getByText('Room connected', { exact: true })).toBeVisible();
  await expect(second.locator('.room-person-chip')).toHaveCount(1);
  await page.close();
  await expect(second.getByText('Room connected', { exact: true })).toBeVisible();
  await expect(second.getByText(/Your session changed/)).toHaveCount(0);
});
