import { expect, test } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';

test('guest upgrades in the room, saves a profile, signs out, and signs back in', async ({ page }) => {
  const username = `test_${Date.now()}`;
  await page.goto('/');
  await page.getByRole('button', { name: 'Create a room', exact: true }).click();
  await page.getByLabel('What should we call you?').fill('Alex');
  await page.getByRole('button', { name: 'Create our little room' }).click();
  await expect(page.getByText('Room connected', { exact: true })).toBeVisible();
  const code = await page.getByTestId('room-code').inputValue();
  await page.getByRole('button', { name: 'Join free', exact: false }).first().click();
  const dialog = page.getByRole('dialog', { name: 'Create a free account' });
  await expect(dialog).toBeVisible();
  await expect(dialog.getByRole('button', { name: 'Continue with Google' })).toBeDisabled();
  await dialog.getByLabel('Username', { exact: true }).fill(username);
  await dialog.getByLabel('Password', { exact: true }).fill('a unique test password');
  await dialog.getByLabel('Nickname', { exact: true }).fill('Account Alex');
  await dialog.getByRole('button', { name: 'Create my free account' }).click();
  await page.getByRole('button', { name: 'I’ve saved my recovery key' }).click();
  await expect(page.getByText('Your free account came along.', { exact: true })).toBeVisible();
  await expect(page.getByText('Room connected', { exact: true })).toBeVisible();
  await expect(page.getByTestId('room-code')).toHaveValue(code);
  await page.getByRole('button', { name: 'My account', exact: true }).first().click();
  await expect(page).toHaveURL(/\/account$/);
  await page.getByLabel('Nickname', { exact: true }).fill('A little Alex');
  await page.getByRole('button', { name: 'rose avatar', exact: true }).click();
  await page.getByRole('button', { name: 'Save my profile', exact: true }).click();
  await expect(page.getByText('Your pixel you is saved. Looking good.')).toBeVisible();
  await page.reload(); await expect(page.getByLabel('Nickname', { exact: true })).toHaveValue('A little Alex');
  const results = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze();
  expect(results.violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => n.failureSummary) }))).toEqual([]);
  await page.screenshot({ path: 'test-results/account-desktop.png', fullPage: true });
  await page.getByRole('button', { name: 'Sign out & keep my guest seat' }).click();
  await expect(page.getByRole('heading', { name: 'A space that remembers you.' })).toBeVisible();
  await page.getByRole('button', { name: 'Sign in', exact: true }).first().click();
  const login = page.getByRole('dialog', { name: 'Sign in to Just Us' });
  await login.getByLabel('Username', { exact: true }).fill(username); await login.getByLabel('Password', { exact: true }).fill('a unique test password');
  await login.getByRole('button', { name: 'Sign in to my account' }).click();
  await expect(page.getByLabel('Nickname', { exact: true })).toHaveValue('A little Alex');
  await page.getByRole('button', { name: 'Back to our room', exact: true }).first().click();
  await expect(page.getByTestId('room-code')).toHaveValue(code);
  await expect(page.getByRole('heading', { name: /A little Alex/ })).toBeVisible();
});

test('mobile account promotion and signup are accessible without blocking guest rooms', async ({ browser }) => {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  const page = await context.newPage();
  await page.goto('/'); await expect(page.getByRole('button', { name: 'Join free', exact: false }).first()).toBeEnabled();
  await expect(page.getByRole('heading', { name: 'Two ways to feel right at home.' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/home-accounts-phone.png', fullPage: true });
  await page.getByRole('button', { name: 'Join free', exact: false }).first().click();
  const results = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze();
  expect(results.violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => n.failureSummary) }))).toEqual([]);
  await page.getByRole('button', { name: 'I’ll stay as a guest for now' }).click();
  await page.getByRole('button', { name: 'Create a room', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Create a room' })).toBeVisible();
  await context.close();
});
